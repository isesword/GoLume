package main

import (
	"fmt"
	"strings"
)

// All physical numeric vectors share one layout and validity contract. Keep
// their storage types explicit: expression promotion does not widen storage.
func generateNumericVectors() []byte {
	var b strings.Builder
	b.WriteString("// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage memory\n\n")
	for _, typ := range []string{"Int8", "Int16", "Int32", "Int64", "Uint8", "Uint16", "Uint32", "Uint64", "Float32", "Float64"} {
		fmt.Fprintf(&b, `// %[1]sVector stores a nullable %[2]s column at its native physical width.
type %[1]sVector struct {
	Values []%[2]s
	Validity Bitmap // nil means all valid
	Encoding Encoding
}

// Len returns the logical row count.
func (v *%[1]sVector) Len() int { return len(v.Values) }

// IsValid reports whether row i is non-NULL.
func (v *%[1]sVector) IsValid(i int) bool { return v.Validity == nil || IsSet(v.Validity, i) }

`, typ, strings.ToLower(typ))
	}
	return []byte(b.String())
}
