package main

import (
	"bytes"
	"fmt"
	"strings"
)

var widenTypes = []string{"Int8", "Int16", "Int32", "Int64", "Uint8", "Uint16", "Uint32", "Uint64", "Float32"}
var widenOps = []struct {
	name, symbol string
	reverse      bool
}{
	{"Add", "+", false}, {"Sub", "-", false}, {"Mul", "*", false}, {"Div", "/", false},
	{"ReverseAdd", "+", true}, {"ReverseSub", "-", true}, {"ReverseMul", "*", true}, {"ReverseDiv", "/", true},
}

func generateWidenAPI() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage kernel\n\nimport \"gocolumn/memory\"")
	fmt.Fprintln(&b, "type widenDispatch struct {")
	for _, typ := range widenTypes {
		t := strings.ToLower(typ)
		fmt.Fprintf(&b, "cast%s func([]%s, []float64, memory.Bitmap)\nmixed%s [9]func([]float64, []%s, []float64, memory.Bitmap)\n", typ, t, typ, t)
	}
	fmt.Fprintln(&b, "pair [ArithmeticDiv+1]func([]float32, []float32, []float64, memory.Bitmap)\nbits, wideBits int\n}")
	fmt.Fprintln(&b, `// Float64WideningCapability reports the backend for conversion and mixed
// arithmetic from typ to Float64. Other types retain scalar conversion.
func (s Set) Float64WideningCapability(typ memory.DataType) KernelCapability {
 switch typ { case memory.TypeInt64, memory.TypeUint64:
if s.d.widen.wideBits != 0 {return KernelCapability{HardwareSIMD:true,VectorBits:s.d.widen.wideBits,Backend:"archsimd-widen-float64"}}
case memory.TypeInt8, memory.TypeInt16, memory.TypeInt32, memory.TypeUint8, memory.TypeUint16, memory.TypeUint32, memory.TypeFloat32:
 if s.d.widen.bits != 0 { return KernelCapability{HardwareSIMD:true, VectorBits:s.d.widen.bits, Backend:"archsimd-widen-float64"} }
 }
 return KernelCapability{Backend:"scalar"}
}`)
	for _, typ := range widenTypes {
		t := strings.ToLower(typ)
		fmt.Fprintf(&b, "// Widen%sToFloat64 converts valid input directly into caller-owned output.\n// Invalid lanes are zeroed. No temporary vector or row storage is allocated.\nfunc (s Set) Widen%sToFloat64(in []%s, out []float64, validity memory.Bitmap) { if len(out)<len(in) { panic(\"kernel: widening output too small\") }; s.d.widen.cast%s(in,out,validity) }\n", typ, typ, t, typ)
		fmt.Fprintf(&b, "// Float64%sArithmetic widens right before Float64 arithmetic. reverse\n// exchanges operand order; exact output aliasing with left is supported.\n// Invalid lanes are zeroed; op must be Add, Sub, Mul, or Div.\nfunc (s Set) Float64%sArithmetic(left []float64, right []%s, out []float64, validity memory.Bitmap, op ArithmeticOp, reverse bool) {\nif len(left)!=len(right)||len(out)<len(left) {panic(\"kernel: mixed arithmetic length mismatch\")}; if op<ArithmeticAdd||op>ArithmeticDiv {panic(\"kernel: unsupported mixed arithmetic\")}; index:=int(op); if reverse {index+=4}; s.d.widen.mixed%s[index](left,right,out,validity)\n}\n", typ, typ, t, typ)
	}
	fmt.Fprintln(&b, `// Float32WidenArithmetic converts both inputs to Float64 before arithmetic.
// It preserves Float64 expression rounding and writes no intermediate vectors.
func (s Set) Float32WidenArithmetic(left,right []float32,out []float64,validity memory.Bitmap,op ArithmeticOp) {
 if len(left)!=len(right)||len(out)<len(left) {panic("kernel: widening arithmetic length mismatch")}; if op<ArithmeticAdd||op>ArithmeticDiv {panic("kernel: unsupported widening arithmetic")}; s.d.widen.pair[op](left,right,out,validity)
}`)
	fmt.Fprintln(&b, "func installWidenScalar(d *dispatch) {")
	for _, typ := range widenTypes {
		fmt.Fprintf(&b, "d.widen.cast%s = scalarWiden%s\n", typ, typ)
		for i, op := range widenOps {
			fmt.Fprintf(&b, "d.widen.mixed%s[%d]=scalarWiden%s%s\n", typ, i+1, typ, op.name)
		}
	}
	for i, op := range widenOps[:4] {
		fmt.Fprintf(&b, "d.widen.pair[%d]=scalarWidenPair%s\n", i+1, op.name)
	}
	fmt.Fprintln(&b, "}")
	for _, typ := range widenTypes {
		t := strings.ToLower(typ)
		fmt.Fprintf(&b, "func scalarWiden%s(in []%s,out []float64,v memory.Bitmap) { for row:=range in {out[row]=0;if validAt(v,row) {out[row]=float64(in[row])}} }\n", typ, t)
		for _, op := range widenOps {
			expr := "left[row] " + op.symbol + " float64(right[row])"
			if op.reverse {
				expr = "float64(right[row]) " + op.symbol + " left[row]"
			}
			fmt.Fprintf(&b, "func scalarWiden%s%s(left []float64,right []%s,out []float64,v memory.Bitmap) {for row:=range left {if validAt(v,row) {out[row]=%s} else {out[row]=0}}}\n", typ, op.name, t, expr)
		}
	}
	for _, op := range widenOps[:4] {
		fmt.Fprintf(&b, "func scalarWidenPair%s(left,right []float32,out []float64,v memory.Bitmap) {for row:=range left {if validAt(v,row) {out[row]=float64(left[row]) %s float64(right[row])} else {out[row]=0}}}\n", op.name, op.symbol)
	}
	return b.Bytes()
}

func widenLoad(arch, typ, slice string) string {
	if arch == "arm64" {
		return widenLoadARM64(typ, slice)
	}
	switch typ {
	case "Int64", "Uint64":
		return "archsimd.Load" + typ + "x4(" + slice + "[row:]).ConvertToFloat64()"
	case "Float32":
		return "archsimd.LoadFloat32x4(" + slice + "[row:]).ConvertToFloat64()"
	case "Int32":
		return "archsimd.LoadInt32x4(" + slice + "[row:]).ConvertToFloat64()"
	case "Uint32":
		return "widenUint32x4(archsimd.LoadUint32x4(" + slice + "[row:]))"
	case "Int8", "Uint8":
		bits := ""
		if typ == "Int8" {
			bits = ".BitsToInt8()"
		}
		extend := ".ExtendLo4ToInt32()"
		if typ == "Uint8" {
			extend = ".ExtendLo4ToUint32().BitsToInt32()"
		}
		return "(archsimd.Uint32x4{}).SetElem(0,*(*uint32)(unsafe.Pointer(&" + slice + "[row]))).ReshapeToUint8s()" + bits + extend + ".ConvertToFloat64()"
	case "Int16", "Uint16":
		bits := ""
		if typ == "Int16" {
			bits = ".BitsToInt16()"
		}
		extend := ".ExtendLo4ToInt32()"
		if typ == "Uint16" {
			extend = ".ExtendLo4ToUint32().BitsToInt32()"
		}
		return "(archsimd.Uint64x2{}).SetElem(0,*(*uint64)(unsafe.Pointer(&" + slice + "[row]))).ReshapeToUint16s()" + bits + extend + ".ConvertToFloat64()"
	}
	panic(typ)
}

func generateWidenSIMD(arch string) []byte {
	var b bytes.Buffer
	if arch == "other" {
		return []byte("//go:build !goexperiment.simd || (!amd64 && !arm64)\n\n// Code generated by internal/cmd/gensimd; DO NOT EDIT.\npackage kernel\nfunc installWidenSIMD(*Set, Mode, int) {}\n")
	}
	fmt.Fprintln(&b, "//go:build goexperiment.simd && "+arch+"\n\n// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage kernel\n\nimport (\"gocolumn/memory\"; \"simd/archsimd\"; \"unsafe\")")
	if arch == "amd64" {
		fmt.Fprintln(&b, `// The conversion intrinsics use 256-bit AVX even though they load four
// 32-bit inputs. Do not install them for forced 128-bit or emulated execution.
func installWidenSIMD(set *Set, mode Mode, vectorBits int) {
 if mode==ModeScalar || !nativeSIMDAvailable() || vectorBits<256 {return}
 set.d.widen.bits=256`)
	} else {
		fmt.Fprintln(&b, `func installWidenSIMD(set *Set, mode Mode, vectorBits int) {
 if mode==ModeScalar || !nativeSIMDAvailable() || vectorBits!=128 {return}
 set.d.widen.bits=128`)
	}
	for _, typ := range widenTypes {
		if typ == "Int64" || typ == "Uint64" {
			if arch == "amd64" {
				fmt.Fprintln(&b, "if archsimd.X86.AVX512() {")
			}
			fmt.Fprintln(&b, "set.d.widen.wideBits=set.d.widen.bits")
		}
		fmt.Fprintf(&b, "set.d.widen.cast%s=simdWiden%s\n", typ, typ)
		for i, op := range widenOps {
			fmt.Fprintf(&b, "set.d.widen.mixed%s[%d]=simdWiden%s%s\n", typ, i+1, typ, op.name)
		}
		if (typ == "Int64" || typ == "Uint64") && arch == "amd64" {
			fmt.Fprintln(&b, "}")
		}
	}
	for i, op := range widenOps[:4] {
		fmt.Fprintf(&b, "set.d.widen.pair[%d]=simdWidenPair%s\n", i+1, op.name)
	}
	fmt.Fprintln(&b, "}")
	if arch == "amd64" {
		fmt.Fprintln(&b, `// Split unsigned lanes into exact low-31-bit and high-bit contributions.
// Uint32.ConvertToFloat64 needs AVX512; this form needs only AVX2.
func widenUint32x4(x archsimd.Uint32x4) archsimd.Float64x4 {
 lo := x.And(archsimd.BroadcastUint32x4(0x7fffffff)).BitsToInt32().ConvertToFloat64()
 hi := x.ShiftAllRight(31).BitsToInt32().ConvertToFloat64()
 return lo.Add(hi.Mul(archsimd.BroadcastFloat64x4(2147483648)))
}
func widenFourValid(v memory.Bitmap,row int) bool {return v==nil || (v[uint(row)/64]>>uint(row%64))&15==15}`)
	} else {
		fmt.Fprintln(&b, `func widenFourValid(v memory.Bitmap,row int) bool {return v==nil || (v[uint(row)/64]>>uint(row%64))&3==3}`)
	}
	for _, typ := range widenTypes {

		t := strings.ToLower(typ)
		fmt.Fprintf(&b, "func simdWiden%s(in []%s,out []float64,v memory.Bitmap) { row:=0;for ;row+4<=len(in);row+=4 {if widenFourValid(v,row) {%s.Store(out[row:])}else {archsimd.ClearAVXUpperBits();for j:=row;j<row+4;j++ {out[j]=0;if validAt(v,j) {out[j]=float64(in[j])}}}}; archsimd.ClearAVXUpperBits();for ;row<len(in);row++ {out[row]=0;if validAt(v,row) {out[row]=float64(in[row])}}}\n", typ, t, widenLoad(arch, typ, "in"))
		for _, op := range widenOps {
			av, bv := "av", "bv"
			if op.reverse {
				av, bv = bv, av
			}
			method := strings.TrimPrefix(op.name, "Reverse")
			scalar := "left[j] " + op.symbol + " float64(right[j])"
			if op.reverse {
				scalar = "float64(right[j]) " + op.symbol + " left[j]"
			}
			fmt.Fprintf(&b, "func simdWiden%s%s(left []float64,right []%s,out []float64,v memory.Bitmap) {row:=0; for ;row+4<=len(left);row+=4 {if widenFourValid(v,row) {av:=archsimd.LoadFloat64x4(left[row:]);bv:=%s;%s.%s(%s).Store(out[row:])}else {archsimd.ClearAVXUpperBits();for j:=row;j<row+4;j++ {if validAt(v,j) {out[j]=%s} else {out[j]=0}}}}; archsimd.ClearAVXUpperBits();for j:=row;j<len(left);j++ {if validAt(v,j) {out[j]=%s} else {out[j]=0}}}\n", typ, op.name, t, widenLoad(arch, typ, "right"), av, method, bv, scalar, scalar)
		}
	}
	for _, op := range widenOps[:4] {
		fmt.Fprintf(&b, "func simdWidenPair%s(left,right []float32,out []float64,v memory.Bitmap) {row:=0; for ;row+4<=len(left);row+=4 {if widenFourValid(v,row) {av:=%s;bv:=%s;av.%s(bv).Store(out[row:])}else {archsimd.ClearAVXUpperBits();for j:=row;j<row+4;j++ {if validAt(v,j) {out[j]=float64(left[j]) %s float64(right[j])} else {out[j]=0}}}};archsimd.ClearAVXUpperBits();for j:=row;j<len(left);j++ {if validAt(v,j) {out[j]=float64(left[j]) %s float64(right[j])} else {out[j]=0}}}\n", op.name, widenLoad(arch, "Float32", "left"), widenLoad(arch, "Float32", "right"), op.name, op.symbol, op.symbol)
	}
	if arch == "arm64" {
		return []byte(strings.NewReplacer("row+4", "row+2", "row+=4", "row+=2", "archsimd.LoadFloat64x4", "archsimd.LoadFloat64x2", "archsimd.ClearAVXUpperBits();", "").Replace(b.String()))
	}
	return b.Bytes()
}

func widenLoadARM64(typ, slice string) string {
	packed := func(bits string) string {
		return "(archsimd.Uint64x2{}).SetElem(0,uint64(*(*uint" + bits + ")(unsafe.Pointer(&" + slice + "[row]))))"
	}
	switch typ {
	case "Int64", "Uint64":
		return "archsimd.Load" + typ + "x2(" + slice + "[row:]).ConvertToFloat64()"
	case "Float32":
		return packed("64") + ".ReshapeToUint32s().BitsToFloat32().ConvertLo2ToFloat64()"
	case "Int32":
		return packed("64") + ".ReshapeToUint32s().BitsToInt32().ExtendLo2ToInt64().ConvertToFloat64()"
	case "Uint32":
		return packed("64") + ".ReshapeToUint32s().ExtendLo2ToUint64().ConvertToFloat64()"
	case "Int8":
		return packed("16") + ".ReshapeToUint8s().BitsToInt8().ExtendLo8ToInt16().ExtendLo4ToInt32().ExtendLo2ToInt64().ConvertToFloat64()"
	case "Uint8":
		return packed("16") + ".ReshapeToUint8s().ExtendLo8ToUint16().ExtendLo4ToUint32().ExtendLo2ToUint64().ConvertToFloat64()"
	case "Int16":
		return packed("32") + ".ReshapeToUint16s().BitsToInt16().ExtendLo4ToInt32().ExtendLo2ToInt64().ConvertToFloat64()"
	case "Uint16":
		return packed("32") + ".ReshapeToUint16s().ExtendLo4ToUint32().ExtendLo2ToUint64().ConvertToFloat64()"
	}
	panic(typ)
}
