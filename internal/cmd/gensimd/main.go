// Command gensimd generates operation-specialized scalar and SIMD kernels.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type numericType struct {
	name   string
	goType string
	field  string
}

type operation struct {
	name     string
	constant string
	symbol   string
}

var (
	check           = flag.Bool("check", false, "fail when generated files are stale")
	list            = flag.Bool("list", false, "print the kernel IDs whose scalar implementation is generated, one per line")
	comparisonTypes = []numericType{
		{"Int8", "int8", "compareInt8"},
		{"Int16", "int16", "compareInt16"},
		{"Int32", "int32", "compareInt32"},
		{"Int64", "int64", "compareInt64"},
		{"Uint8", "uint8", "compareUint8"},
		{"Uint16", "uint16", "compareUint16"},
		{"Uint32", "uint32", "compareUint32"},
		{"Uint64", "uint64", "compareUint64"},
		{"Float64", "float64", "compareFloat64"},
	}
	comparisonOps = []operation{
		{"GT", "CompareGT", ">"},
		{"GE", "CompareGE", ">="},
		{"LT", "CompareLT", "<"},
		{"LE", "CompareLE", "<="},
		{"EQ", "CompareEQ", "=="},
	}
)

func main() {
	flag.Parse()
	if *list {
		for _, id := range generatedKernelIDs() {
			fmt.Println(id)
		}
		return
	}
	root, err := repositoryRoot()
	if err != nil {
		panic(err)
	}
	if err := os.Chdir(root); err != nil {
		panic(err)
	}
	outputs := map[string][]byte{
		"kernel/zz_generated_scale_amd64.go":           generateScaleSIMD("amd64"),
		"kernel/zz_generated_scale_arm64.go":           generateScaleSIMD("arm64"),
		"kernel/zz_generated_scale_other.go":           generateScaleSIMD("other"),
		"kernel/zz_generated_checked_integer_amd64.go": generateCheckedInteger("amd64"),
		"kernel/zz_generated_checked_integer_arm64.go": generateCheckedInteger("arm64"),
		"kernel/zz_generated_checked_integer_other.go": generateCheckedInteger("other"),
		"kernel/zz_generated_widen.go":                 generateWidenAPI(),
		"kernel/zz_generated_widen_arm64.go":           generateWidenSIMD("arm64"),
		"kernel/zz_generated_widen_amd64.go":           generateWidenSIMD("amd64"),
		"kernel/zz_generated_widen_other.go":           generateWidenSIMD("other"),
		"kernel/zz_generated_minmax_narrow_amd64.go":   generateNarrowMinMaxSIMD("amd64"),
		"kernel/zz_generated_minmax_narrow_arm64.go":   generateNarrowMinMaxSIMD("arm64"),
		"kernel/zz_generated_minmax_narrow_other.go":   generateNarrowMinMaxSIMD("other"),
		"kernel/zz_generated_minmax_simd.go":           generateMinMaxSIMD(),
		"memory/zz_generated_numeric.go":               generateNumericVectors(),
		"kernel/zz_generated_scalar.go":                generateScalar(),
		"kernel/zz_generated_simd.go":                  generatePortableSIMD(),
		"kernel/zz_generated_simd_amd64.go":            generateAMD64SIMD(),
		"kernel/zz_generated_simd_arm64.go":            generateArm64SIMD(),
		"kernel/zz_generated_simd_arch_other.go":       generateOtherArch(),
	}
	for path, source := range outputs {
		formatted, err := format.Source(source)
		if err != nil {
			panic(fmt.Errorf("format %s: %w\n%s", path, err, source))
		}
		if *check {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, formatted) {
				fmt.Fprintf(os.Stderr, "%s is stale; run go generate ./kernel\n", path)
				os.Exit(1)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			panic(err)
		}
		if err := os.WriteFile(path, formatted, 0o644); err != nil {
			panic(err)
		}
	}
}

func repositoryRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from working directory")
		}
		dir = parent
	}
}

func generateOtherArch() []byte {
	b := header("goexperiment.simd && !amd64 && !arm64")
	b.WriteString("func installGeneratedArchSIMD(*Set, Mode, int) {}\n")
	return []byte(b.String())
}

func header(build string) *strings.Builder {
	var b strings.Builder
	if build != "" {
		fmt.Fprintf(&b, "//go:build %s\n\n", build)
	}
	b.WriteString("// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage kernel\n\n")
	return &b
}

func generateScalar() []byte {
	b := header("")
	b.WriteString("import (\n\t\"gocolumn/memory\"\n\t\"math\"\n\t\"math/bits\"\n)\n\n")
	b.WriteString("func installGeneratedScalar(d *dispatch) {\n")
	for _, typ := range comparisonTypes {
		for _, op := range comparisonOps {
			fmt.Fprintf(b, "\td.%s[%s] = scalar%s%s\n", typ.field, op.constant, typ.name, op.name)
		}
	}
	for _, typ := range []numericType{{"Int32", "int32", "arithmeticInt32"}, {"Int64", "int64", "arithmeticInt64"}, {"Uint32", "uint32", "arithmeticUint32"}, {"Uint64", "uint64", "arithmeticUint64"}} {
		for _, op := range []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}} {
			fmt.Fprintf(b, "\td.%s[%s] = scalar%s%s\n", typ.field, op.constant, typ.name, op.name)
		}
	}
	for _, op := range []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}, {"Div", "ArithmeticDiv", "/"}} {
		fmt.Fprintf(b, "\td.arithmeticFloat64[%s] = scalarFloat64%s\n", op.constant, op.name)
		fmt.Fprintf(b, "\td.arithmeticFloat32[%s] = scalarFloat32%s\n", op.constant, op.name)
	}
	for _, op := range comparisonOps {
		fmt.Fprintf(b, "\td.stringByteLength[%s] = scalarStringByteLength%s\n", op.constant, op.name)
		fmt.Fprintf(b, "\td.stringUTF8Length[%s] = scalarStringUTF8Length%s\n", op.constant, op.name)
	}
	b.WriteString("}\n\n")
	for _, typ := range comparisonTypes {
		for _, op := range comparisonOps {
			fmt.Fprintf(b, `func scalar%s%s(values []%s, validity memory.Bitmap, out memory.Bitmap, threshold %s) int {
	prepareComparison(len(values), out)
	selected := 0
	for row, value := range values {
		if validAt(validity, row) && value %s threshold {
			setSelected(out, row, &selected)
		}
	}
	return selected
}

`, typ.name, op.name, typ.goType, typ.goType, op.symbol)
		}
	}
	for _, typ := range []numericType{{"Int32", "int32", ""}, {"Int64", "int64", ""}, {"Uint32", "uint32", ""}, {"Uint64", "uint64", ""}} {
		for _, op := range []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}} {
			fmt.Fprint(b, integerArithmetic(typ, op))
		}
	}
	for _, op := range []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}, {"Div", "ArithmeticDiv", "/"}} {
		fmt.Fprintf(b, `func scalarFloat64%s(left, right, out []float64, validity memory.Bitmap) {
	if len(left) != len(right) || len(out) < len(left) {
		panic("kernel: float64 arithmetic length mismatch")
	}
	for row, a := range left {
		if !validAt(validity, row) {
			out[row] = 0
			continue
		}
		out[row] = a %s right[row]
	}
}

`, op.name, op.symbol)
	}
	for _, op := range []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}, {"Div", "ArithmeticDiv", "/"}} {
		fmt.Fprintf(b, `func scalarFloat32%s(left, right, out []float32, validity memory.Bitmap) {
	if len(left) != len(right) || len(out) < len(left) {
		panic("kernel: float32 arithmetic length mismatch")
	}
	for row, a := range left {
		if !validAt(validity, row) { out[row] = 0; continue }
		out[row] = a %s right[row]
	}
}

`, op.name, op.symbol)
	}
	for _, op := range comparisonOps {
		for _, kind := range []struct {
			name   string
			length string
		}{{"Byte", "int64(hi - lo)"}, {"UTF8", "int64(runeCountBytes(data[lo:hi]))"}} {
			fmt.Fprintf(b, `func scalarString%sLength%s(offsets []uint32, data []byte, validity, out memory.Bitmap, literal int64) int {
	if len(offsets) == 0 {
		prepareComparison(0, out)
		return 0
	}
	rows := len(offsets) - 1
	prepareComparison(rows, out)
	selected := 0
	for row := 0; row < rows; row++ {
		if !validAt(validity, row) {
			continue
		}
		lo, hi := offsets[row], offsets[row+1]
		if lo > hi || int(hi) > len(data) {
			panic("kernel: invalid string offsets")
		}
		if %s %s literal {
			setSelected(out, row, &selected)
		}
	}
	return selected
}

`, kind.name, op.name, kind.length, op.symbol)
		}
	}
	return []byte(b.String())
}

func integerArithmetic(typ numericType, op operation) string {
	var calc string
	switch typ.name {
	case "Int32":
		calc = fmt.Sprintf("wide := int64(a) %s int64(right[row])\n\t\tfailed := wide < math.MinInt32 || wide > math.MaxInt32\n\t\tvalue := int32(wide)", op.symbol)
	case "Uint32":
		if op.name == "Sub" {
			calc = "b := right[row]\n\t\tvalue := a - b\n\t\tfailed := a < b"
		} else {
			calc = fmt.Sprintf("wide := uint64(a) %s uint64(right[row])\n\t\tfailed := wide > math.MaxUint32\n\t\tvalue := uint32(wide)", op.symbol)
		}
	case "Int64":
		switch op.name {
		case "Add":
			calc = "b := right[row]\n\t\tvalue := a + b\n\t\tfailed := (b > 0 && a > math.MaxInt64-b) || (b < 0 && a < math.MinInt64-b)"
		case "Sub":
			calc = "b := right[row]\n\t\tvalue := a - b\n\t\tfailed := (b > 0 && a < math.MinInt64+b) || (b < 0 && a > math.MaxInt64+b)"
		case "Mul":
			calc = "b := right[row]\n\t\tvalue := a * b\n\t\tfailed := (a == math.MinInt64 && b == -1) || (b == math.MinInt64 && a == -1) || (a != 0 && value/a != b)"
		}
	case "Uint64":
		switch op.name {
		case "Add":
			calc = "value, carry := bits.Add64(a, right[row], 0)\n\t\tfailed := carry != 0"
		case "Sub":
			calc = "value, borrow := bits.Sub64(a, right[row], 0)\n\t\tfailed := borrow != 0"
		case "Mul":
			calc = "hi, value := bits.Mul64(a, right[row])\n\t\tfailed := hi != 0"
		}
	}
	return fmt.Sprintf(`func scalar%s%s(left, right, out []%s, validity, overflow memory.Bitmap) int {
	prepareIntegerArithmetic(len(left), len(left), len(right), len(out), overflow)
	if validity == nil && overflow == nil {
		first := -1
		for row, a := range left {
			%s
			if failed && first < 0 {
				first = row
			}
			out[row] = value
		}
		return first
	}
	first := -1
	for wi := 0; wi < memory.WordsFor(len(left)); wi++ {
		base := wi * 64
		wordRows := min(64, len(left)-base)
		var failedWord uint64
		for offset := 0; offset < wordRows; offset++ {
			row := base + offset
			a := left[row]
			%s
			if failed {
				failedWord |= uint64(1) << uint(offset)
			}
			out[row] = value
		}
		validWord := bitmapWord(validity, wi) & memory.TailMask(wordRows)
		failedWord &= validWord
		if overflow != nil {
			overflow[wi] = failedWord
		}
		if first < 0 && failedWord != 0 {
			first = base + bits.TrailingZeros64(failedWord)
		}
		invalid := (^validWord) & memory.TailMask(wordRows)
		for invalid != 0 {
			bit := bits.TrailingZeros64(invalid)
			out[base+bit] = 0
			invalid &= invalid - 1
		}
	}
	return first
}

`, typ.name, op.name, typ.goType, calc, calc)
}

func generatePortableSIMD() []byte {
	b := header("goexperiment.simd")
	b.WriteString("import (\n\t\"gocolumn/memory\"\n\t\"math/bits\"\n\t\"simd\"\n)\n\n")
	floatTypes := []numericType{{"Float32", "float32", "arithmeticFloat32"}, {"Float64", "float64", "arithmeticFloat64"}}
	arithmeticOps := []operation{{"Add", "ArithmeticAdd", "+"}, {"Sub", "ArithmeticSub", "-"}, {"Mul", "ArithmeticMul", "*"}, {"Div", "ArithmeticDiv", "/"}}
	literalTypes := append([]numericType{{"Float32", "float32", "compareFloat32"}}, comparisonTypes...)
	// Int32, Uint32 and Float32 keep their existing portable implementations.
	// Every other column backend uses the same metadata as literal comparisons.
	var columnTypes []numericType
	for _, typ := range comparisonTypes {
		if typ.name != "Int32" && typ.name != "Uint32" {
			columnTypes = append(columnTypes, typ)
		}
	}
	b.WriteString(`func installGeneratedPortableSIMD(set *Set, mode Mode, vectorBits int) {
 if mode == ModeScalar || !nativeSIMDAvailable() { return }
 capability := KernelCapability{HardwareSIMD: true, VectorBits: vectorBits, Backend: "portable-simd"}
`)
	for _, typ := range floatTypes {
		for _, op := range arithmeticOps {
			fmt.Fprintf(b, "set.d.%s[%s] = simd%s%s\n", typ.field, op.constant, typ.name, op.name)
			fmt.Fprintf(b, "id%s%s, _ := ArithmeticID(memory.Type%s, %s)\nset.setCapability(id%s%s, capability)\n", typ.name, op.name, typ.name, op.constant, typ.name, op.name)
		}
	}
	for _, typ := range literalTypes {
		for _, op := range comparisonOps {
			fmt.Fprintf(b, "set.d.%s[%s] = simd%s%s\n", typ.field, op.constant, typ.name, op.name)
			fmt.Fprintf(b, "id%s%s, _ := ComparisonID(memory.Type%s, %s)\nset.setCapability(id%s%s, capability)\n", typ.name, op.name, typ.name, op.constant, typ.name, op.name)
		}
	}
	for _, typ := range columnTypes {
		for _, op := range comparisonOps {
			fmt.Fprintf(b, "set.d.%sColumns[%s] = simd%sColumns%s\nset.d.caps.columns[id%s%s] = capability\n", typ.field, op.constant, typ.name, op.name, typ.name, op.name)
		}
	}
	b.WriteString("}\n\n")
	for _, typ := range floatTypes {
		for _, op := range arithmeticOps {
			fmt.Fprintf(b, `func simd%s%s(left, right, out []%s, validity memory.Bitmap) {
 if len(left) != len(right) || len(out) < len(left) { panic("kernel: %s arithmetic length mismatch") }
 lanes := simd.%ss{}.Len()
 row := 0
 for ; row+lanes <= len(left); row += lanes {
  simd.Load%ss(left[row:]).%s(simd.Load%ss(right[row:])).Store(out[row:])
 }
 for ; row < len(left); row++ { out[row] = left[row] %s right[row] }
 clearInvalid%s(out[:len(left)], validity)
}

`, typ.name, op.name, typ.goType, typ.goType, typ.name, typ.name, op.name, typ.name, op.symbol, typ.name)
		}
	}
	for _, typ := range literalTypes {
		width := strings.TrimLeft(typ.name, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
		for _, op := range comparisonOps {
			broadcast := fmt.Sprintf("simd.Broadcast%ss(threshold)", typ.name)
			vectorLoad := fmt.Sprintf("simd.Load%ss(values[base+off:])", typ.name)
			if typ.name == "Uint8" && op.name != "EQ" {
				// Portable Uint8s has equality but no ordered comparisons.
				// Flipping the sign bit maps unsigned byte order to signed order.
				broadcast = "simd.BroadcastInt8s(int8(threshold ^ 0x80))"
				vectorLoad += ".Xor(simd.BroadcastUint8s(0x80)).BitsToInt8()"
			}
			fmt.Fprintf(b, `func simd%s%s(values []%s, validity memory.Bitmap, out memory.Bitmap, threshold %s) int {
 lanes := simd.%ss{}.Len()
 if len(values) < lanes { return scalar%s%s(values, validity, out, threshold) }
 words := prepareComparison(len(values), out)
 vectorThreshold := %s
 var laneMaskStorage [64]int%s
 laneMask := laneMaskStorage[:lanes]
 selected := 0
 for wi := 0; wi < words; wi++ {
  base := wi * 64
  wordRows := min(64, len(values)-base)
  var selectedWord uint64
  off := 0
  for ; off+lanes <= wordRows; off += lanes {
   %s.%s(vectorThreshold).ToInt%ss().Store(laneMask)
   for lane := 0; lane < lanes; lane++ {
    if laneMask[lane] < 0 { selectedWord |= uint64(1) << uint(off+lane) }
   }
  }
  for ; off < wordRows; off++ {
   if values[base+off] %s threshold { selectedWord |= uint64(1) << uint(off) }
  }
  selectedWord &= bitmapWord(validity, wi) & memory.TailMask(wordRows)
  out[wi] = selectedWord
  selected += bits.OnesCount64(selectedWord)
 }
 return selected
}

`, typ.name, op.name, typ.goType, typ.goType, typ.name, typ.name, op.name, broadcast, width, vectorLoad, op.nameForArch(), width, op.symbol)
		}
	}
	for _, typ := range columnTypes {
		width := strings.TrimLeft(typ.name, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
		for _, op := range comparisonOps {
			leftLoad := fmt.Sprintf("simd.Load%ss(left[base+off:])", typ.name)
			rightLoad := fmt.Sprintf("simd.Load%ss(right[base+off:])", typ.name)
			if typ.name == "Uint8" && op.name != "EQ" {
				// Both operands must be mapped from unsigned to signed byte order.
				leftLoad += ".Xor(simd.BroadcastUint8s(0x80)).BitsToInt8()"
				rightLoad += ".Xor(simd.BroadcastUint8s(0x80)).BitsToInt8()"
			}
			fmt.Fprintf(b, `func simd%sColumns%s(left, right []%s, leftValid, rightValid, out memory.Bitmap) int {
 if len(left) != len(right) { panic("kernel: %s column comparison length mismatch") }
 lanes := simd.%ss{}.Len()
 if len(left) < lanes { return scalar%sColumns%s(left, right, leftValid, rightValid, out) }
 words := prepareComparison(len(left), out)
 var laneMaskStorage [64]int%s
 laneMask := laneMaskStorage[:lanes]
 selected := 0
 for wi := 0; wi < words; wi++ {
  base := wi * 64
  rows := min(64, len(left)-base)
  validWord := bitmapWord(leftValid, wi) & bitmapWord(rightValid, wi) & memory.TailMask(rows)
  // prepareComparison cleared every logical output word, including skipped words.
  if validWord == 0 { continue }
  var word uint64
  off := 0
  for ; off+lanes <= rows; off += lanes {
   %s.%s(%s).ToInt%ss().Store(laneMask)
   for lane := 0; lane < lanes; lane++ {
    if laneMask[lane] < 0 { word |= uint64(1) << uint(off+lane) }
   }
  }
  for ; off < rows; off++ {
   if left[base+off] %s right[base+off] { word |= uint64(1) << uint(off) }
  }
  word &= validWord
  out[wi] = word
  selected += bits.OnesCount64(word)
 }
 return selected
}

`, typ.name, op.name, typ.goType, typ.goType, typ.name, typ.name, op.name, width, leftLoad, op.nameForArch(), rightLoad, width, op.symbol)
		}
	}
	return []byte(b.String())
}

func generateArm64SIMD() []byte {
	b := header("goexperiment.simd && arm64")
	b.WriteString("import (\n\t\"gocolumn/memory\"\n\t\"math/bits\"\n\t\"simd/archsimd\"\n)\n\n")
	winners := []struct {
		typ       numericType
		op        operation
		vector    string
		broadcast string
	}{}
	for _, typ := range []numericType{{"Int32", "int32", "compareInt32"}, {"Uint32", "uint32", "compareUint32"}} {
		for _, op := range comparisonOps {
			if typ.name == "Int32" && op.name == "EQ" {
				continue
			}
			winners = append(winners, struct {
				typ               numericType
				op                operation
				vector, broadcast string
			}{typ, op, typ.name + "x4", "Broadcast" + typ.name + "x4"})
		}
	}
	b.WriteString(`func installGeneratedArchSIMD(set *Set, mode Mode, vectorBits int) {
	if mode == ModeScalar || vectorBits < 128 {
		return
	}
	capability := KernelCapability{HardwareSIMD: true, VectorBits: 128, Backend: "archsimd-arm64-mask"}
`)
	for _, winner := range winners {
		fmt.Fprintf(b, "\tset.d.%s[%s] = simdArm%s%s\n", winner.typ.field, winner.op.constant, winner.typ.name, winner.op.name)
		fmt.Fprintf(b, "\tid%s%s, _ := ComparisonID(memory.Type%s, %s)\n\tset.setCapability(id%s%s, capability)\n", winner.typ.name, winner.op.name, winner.typ.name, winner.op.constant, winner.typ.name, winner.op.name)
	}
	b.WriteString("}\n\n")
	for _, winner := range winners {
		fmt.Fprintf(b, `func simdArm%s%s(values []%s, validity memory.Bitmap, out memory.Bitmap, threshold %s) int {
	words := prepareComparison(len(values), out)
	thresholdVector := archsimd.%s(threshold)
	selected := 0
	for wi := 0; wi < words; wi++ {
		base := wi * 64
		wordRows := min(64, len(values)-base)
		var selectedWord uint64
		off := 0
		for ; off+4 <= wordRows; off += 4 {
			mask := archsimd.Load%s(values[base+off:]).%s(thresholdVector).ToInt32x4()
			laneBits := (uint64(uint32(mask.GetElem(0))) >> 31) |
				(uint64(uint32(mask.GetElem(1)))>>31)<<1 |
				(uint64(uint32(mask.GetElem(2)))>>31)<<2 |
				(uint64(uint32(mask.GetElem(3)))>>31)<<3
			selectedWord |= laneBits << uint(off)
		}
		for ; off < wordRows; off++ {
			if values[base+off] %s threshold {
				selectedWord |= uint64(1) << uint(off)
			}
		}
		selectedWord &= bitmapWord(validity, wi)
		if wordRows < 64 {
			selectedWord &= memory.TailMask(wordRows)
		}
		out[wi] = selectedWord
		selected += bits.OnesCount64(selectedWord)
	}
	return selected
}

`, winner.typ.name, winner.op.name, winner.typ.goType, winner.typ.goType, winner.broadcast, winner.vector, winner.op.nameForArch(), winner.op.symbol)
	}
	return []byte(b.String())
}

func (op operation) nameForArch() string {
	switch op.name {
	case "GT":
		return "Greater"
	case "GE":
		return "GreaterEqual"
	case "LT":
		return "Less"
	case "LE":
		return "LessEqual"
	case "EQ":
		return "Equal"
	default:
		panic(op.name)
	}
}

// generatedKernelIDs returns the sorted kernel IDs whose scalar
// implementation is emitted into kernel/zz_generated_scalar.go. The
// list is derived from the same type and operation tables that drive
// generateScalar, so it cannot drift from the generated code.
func generatedKernelIDs() []string {
	var ids []string
	for _, typ := range comparisonTypes {
		for _, op := range comparisonOps {
			ids = append(ids, "compare-"+strings.ToLower(typ.name)+"-"+strings.ToLower(op.name))
		}
	}
	for _, typ := range []string{"int32", "int64", "uint32", "uint64"} {
		for _, op := range []string{"add", "sub", "mul"} {
			ids = append(ids, "arithmetic-"+typ+"-"+op)
		}
	}
	for _, typ := range []string{"float64", "float32"} {
		for _, op := range []string{"add", "sub", "mul", "div"} {
			ids = append(ids, "arithmetic-"+typ+"-"+op)
		}
	}
	ids = append(ids, "string-byte-length", "string-utf8-length")
	sort.Strings(ids)
	return ids
}
