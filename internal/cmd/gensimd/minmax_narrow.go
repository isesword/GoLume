package main

import (
	"bytes"
	"fmt"
	"strings"
)

// generateNarrowMinMaxSIMD widens bounded typed loads into registers, never a
// row buffer. Both signed and unsigned narrow integers fit exactly in int32.
func generateNarrowMinMaxSIMD(arch string) []byte {
	var b bytes.Buffer
	tag := arch
	if arch == "other" {
		tag = "!amd64 && !arm64"
	}
	fmt.Fprintf(&b, "// Code generated by gensimd; DO NOT EDIT.\n//go:build goexperiment.simd && %s\n\npackage kernel\n", tag)
	if arch == "other" {
		b.WriteString("func installNarrowMinMaxSIMD(set *Set, vectorBits int) {}\n")
		return b.Bytes()
	}
	b.WriteString(`import ("gocolumn/memory"; "math"; "simd/archsimd"; "unsafe")

// installNarrowMinMaxSIMD is called only behind the native CPU and width guards.
func installNarrowMinMaxSIMD(set *Set, vectorBits int) {
 switch vectorBits {
`)
	widths := []int{128}
	if arch == "amd64" {
		widths = append(widths, 256, 512)
	}
	types := []string{"Int8", "Int16", "Uint8", "Uint16"}
	for _, width := range widths {
		fmt.Fprintf(&b, "case %d:\n", width)
		for _, t := range types {
			fmt.Fprintf(&b, "set.d.minMax%sMasked = minMax%sMaskedNative%d\n", t, t, width)
		}
	}
	b.WriteString(`default: return
 }
 for _, typ := range []memory.DataType{memory.TypeInt8, memory.TypeInt16, memory.TypeUint8, memory.TypeUint16} {
 id, _ := MinMaxID(typ)
 set.setCapability(id, KernelCapability{HardwareSIMD:true, VectorBits:vectorBits, Backend:"archsimd-widen-minmax"})
 }
}
`)
	for _, width := range widths {
		lanes := width / 32
		for _, t := range types {
			low := strings.ToLower(t)
			inputBits := 8
			if strings.HasSuffix(t, "16") {
				inputBits = 16
			}
			signed := strings.HasPrefix(t, "Int")
			hi := "0"
			if signed {
				hi = "math.Min" + t
			}
			var load string
			if lanes*inputBits < 128 {
				bits := lanes * inputBits
				load = fmt.Sprintf("(archsimd.Uint%dx%d{}).SetElem(0, *(*uint%d)(unsafe.Pointer(&v[off]))).ReshapeToUint%ds()", bits, 128/bits, bits, inputBits)
				if signed {
					load += fmt.Sprintf(".BitsToInt%d()", inputBits)
				}
				if arch == "arm64" && inputBits == 8 {
					prefix := "Uint"
					if signed {
						prefix = "Int"
					}
					load += fmt.Sprintf(".ExtendLo8To%s16()", prefix)
				}
				prefix := "Uint"
				if signed {
					prefix = "Int"
				}
				load += fmt.Sprintf(".ExtendLo%dTo%s32()", lanes, prefix)
			} else {
				prefix := "Uint"
				if signed {
					prefix = "Int"
				}
				load = fmt.Sprintf("archsimd.Load%sx%d(v[off:]).ExtendTo%s32()", t, lanes, prefix)
			}
			if !signed {
				load += ".BitsToInt32()"
			}
			fmt.Fprintf(&b, `
// minMax%sMaskedNative%d loads exactly %d values per iteration. Widening
// stays in registers; the loop bound excludes partial loads and scalar tails
// preserve selection bits without per-row scratch or heap allocations.
func minMax%sMaskedNative%d(v []%s, mask uint64) (%s,%s) {
 mask = checkedMinMaxMask(len(v),mask)
 if mask == 0 { return 0,0 }
 if len(v) < %d { return scalarMinMaxMasked(v,mask) }
 lo := archsimd.BroadcastInt32x%d(math.Max%s)
 hi := archsimd.BroadcastInt32x%d(%s)
 off := 0
 if mask == memory.TailMask(len(v)) {
  for ; off+%d <= len(v); off += %d {
   x := %s
   lo = lo.Min(x)
   hi = hi.Max(x)
  }
 } else {
`, t, width, lanes, t, width, low, low, low, lanes, lanes, t, lanes, hi, lanes, lanes, load)
			if width != 512 {
				fmt.Fprintf(&b, "weights := archsimd.LoadUint32x%d(sumWeights32[:])\n", lanes)
			}
			fmt.Fprintf(&b, "for ; off+%d <= len(v); off += %d {\n", lanes, lanes)
			if width == 512 {
				b.WriteString("selected := archsimd.Mask32x16FromBits(uint16(mask>>uint(off)))\n")
			} else {
				fmt.Fprintf(&b, "selected := archsimd.BroadcastUint32x%d(uint32(mask>>uint(off))).And(weights).NotEqual(archsimd.Uint32x%d{})\n", lanes, lanes)
			}
			fmt.Fprintf(&b, "x := %s\nlo = lo.Min(x).IfElse(selected,lo)\nhi = hi.Max(x).IfElse(selected,hi)\n}\n}\n", load)
			fmt.Fprintf(&b, "a,z := reduceNarrowMinMax%d(lo,hi)\nfor ; off < len(v); off++ {\nif mask&(uint64(1)<<uint(off)) != 0 { x := int32(v[off]); a = min(a,x); z = max(z,x) }\n}\nreturn %s(a),%s(z)\n}\n", width, low, low)
		}
		fmt.Fprintf(&b, "func reduceNarrowMinMax%d(lo,hi archsimd.Int32x%d) (int32,int32) {\n", width, lanes)
		if arch == "arm64" {
			b.WriteString("return lo.ReduceMin(),hi.ReduceMax()\n}\n")
			continue
		}
		switch width {
		case 512:
			b.WriteString("p := lo.GetLo().Min(lo.GetHi()); q := hi.GetLo().Max(hi.GetHi()); a := p.GetLo().Min(p.GetHi()); z := q.GetLo().Max(q.GetHi())\n")
		case 256:
			b.WriteString("a := lo.GetLo().Min(lo.GetHi()); z := hi.GetLo().Max(hi.GetHi())\n")
		default:
			b.WriteString("a,z := lo,hi\n")
		}
		b.WriteString(`a = a.Min(a.PermuteScalars(2,3,0,1)); z = z.Max(z.PermuteScalars(2,3,0,1))
a = a.Min(a.PermuteScalars(1,0,3,2)); z = z.Max(z.PermuteScalars(1,0,3,2))
l,h := finishMinMaxAVX(uint64(a.GetElem(0)),uint64(z.GetElem(0)))
return int32(l),int32(h)
}
`)
	}
	return b.Bytes()
}
