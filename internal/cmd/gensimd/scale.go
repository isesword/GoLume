package main

import (
	"bytes"
	"fmt"
)

// Scaling differs from checked arithmetic: stop before the first failing store,
// leave that row and the entire suffix intact, and preserve NULL payloads.
func generateScaleSIMD(arch string) []byte {
	var b bytes.Buffer
	build := "goexperiment.simd && " + arch
	if arch == "other" {
		build = "goexperiment.simd && !amd64 && !arm64"
	}
	fmt.Fprintf(&b, "//go:build %s\n\n// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage kernel\n\n", build)
	if arch == "other" {
		b.WriteString("func installScaleSIMD(*Set, Mode, int) {}\n")
		return b.Bytes()
	}
	b.WriteString("import (\"gocolumn/memory\"; \"math\"; \"math/bits\"; \"simd/archsimd\")\n\n")
	widths := []int{128}
	if arch == "amd64" {
		widths = []int{128, 256, 512}
	}
	b.WriteString("func installScaleSIMD(set *Set, mode Mode, vectorBits int) {\nif mode == ModeScalar || !nativeSIMDAvailable() {return}\n")
	if arch == "amd64" {
		b.WriteString("if !amd64ComparisonWidthSupported(vectorBits) {return}\n")
	}
	b.WriteString("switch vectorBits {\n")
	for _, w := range widths {
		fmt.Fprintf(&b, "case %d:\nset.d.scaleInt64=scale%s%d\nset.setCapability(KernelInt64Scale,KernelCapability{HardwareSIMD:true,VectorBits:%d,Backend:%q})\n", w, arch, w, w, "archsimd-"+arch+"-scale")
	}
	b.WriteString("}\n}\n")
	for _, w := range widths {
		n := w / 64
		fmt.Fprintf(&b, `func scale%s%d(values []int64, validity memory.Bitmap, factor int64) int {
// Factor one is a no-op. The other factors, including zero and negation,
// use SIMD once there is a full vector. Avoid dividing by zero or -1.
if factor == 1 {return -1}
if len(values)<%d { return scalarInt64Scale(values,validity,factor) }
low,high := int64(math.MinInt64),int64(math.MaxInt64)
switch factor {
case 0:
case -1: low++
default: low,high=low/factor,high/factor; if factor<0 {low,high=high,low}
}
if validity==nil {return scaleDense%s%d(values,factor,low,high)}
lo,hi:=archsimd.BroadcastInt64x%d(low),archsimd.BroadcastInt64x%d(high)
b:=archsimd.BroadcastUint64x%d(uint64(factor))
weights:=archsimd.LoadUint64x%d(sumWeights64[:])
`, arch, w, n, arch, w, n, n, n, n)
		if arch == "amd64" && w < 512 {
			b.WriteString("bl,bh:=b.ReshapeToUint32s(),b.ShiftAllRight(32).ReshapeToUint32s()\n")
		}
		if arch == "arm64" {
			b.WriteString("b32:=b.ReshapeToUint32s()\nbl,bh:=b32.ConcatEven(b32),b32.ConcatOdd(b32)\n")
		}
		b.WriteString(`for base:=0; base<len(values); base+=64 {
rows:=min(64,len(values)-base)
word:=bitmapWord(validity,base>>6)&memory.TailMask(rows)
if word==0 {continue}
`)
		fmt.Fprintf(&b, "if word==memory.TailMask(rows) { if failed:=scaleDense%s%d(values[base:base+rows],factor,low,high);failed>=0 {return base+failed};continue}\noff:=0\n", arch, w)
		if w < 512 {
			emitScaleMaskedGroup(&b, arch, w)
		}
		fmt.Fprintf(&b, "for ; off+%d<=rows; off+=%d {\nactive:=word>>uint(off)&%d\nif active==0 {continue}\nx:=archsimd.LoadInt64x%d(values[base+off:])\nfailed:=x.Less(lo).Or(x.Greater(hi))\n", n, n, (1<<n)-1, n)
		if arch == "amd64" {
			b.WriteString("bad:=uint64(failed.ToBits())&active\n")
		} else {
			b.WriteString("mask:=failed.ToInt64x2()\nbad:=((uint64(mask.GetElem(0))>>63)|((uint64(mask.GetElem(1))>>63)<<1))&active\n")
		}
		b.WriteString(`if bad!=0 {
// Nothing from this vector has been stored. Complete only the valid prefix
// so failure, NULL payloads, and every later row remain exactly scalar.
end:=bits.TrailingZeros64(bad)
`)
		if arch == "amd64" {
			b.WriteString("archsimd.ClearAVXUpperBits()\n")
		}
		b.WriteString("for lane:=0; lane<end; lane++ { if active&(uint64(1)<<uint(lane))!=0 {values[base+off+lane]*=factor} }\nreturn base+off+end\n}\n")
		if arch == "amd64" && w == 512 {
			b.WriteString("result:=x.ToBits().Mul(b).BitsToInt64()\n")
		} else if arch == "amd64" {
			b.WriteString("a:=x.ToBits()\nal,ah:=a.ReshapeToUint32s(),a.ShiftAllRight(32).ReshapeToUint32s()\n// Only the low 64 bits are needed after the signed bound check.\nresult:=al.MulWidenEven(bl).Add(ah.MulWidenEven(bl).Add(al.MulWidenEven(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		} else {
			b.WriteString("a32:=x.ToBits().ReshapeToUint32s()\nal,ah:=a32.ConcatEven(a32),a32.ConcatOdd(a32)\nresult:=al.MulWidenLo(bl).Add(ah.MulWidenLo(bl).Add(al.MulWidenLo(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		}
		fmt.Fprintf(&b, "if active!=%d {selected:=archsimd.BroadcastUint64x%d(active).And(weights).NotEqual(archsimd.Uint64x%d{})\nresult=result.IfElse(selected,x)}\nresult.Store(values[base+off:])\n}\n", (1<<n)-1, n, n)
		if arch == "amd64" {
			b.WriteString("archsimd.ClearAVXUpperBits()\n")
		}
		b.WriteString("for ;off<rows;off++ {if word&(uint64(1)<<uint(off))==0 {continue}\nrow:=base+off\nx:=values[row]\nif x<low || x>high {return row}\nvalues[row]=x*factor\n}\n}\n")
		if arch == "amd64" {
			b.WriteString("archsimd.ClearAVXUpperBits()\n")
		}
		b.WriteString("return -1\n}\n\n")
		emitScaleDense(&b, arch, w)
	}
	return b.Bytes()
}

// Dense groups combine eight lanes' overflow flags before writing anything.
// This amortizes loop/bounds checks on AVX2 without changing the failure prefix.
func emitScaleDense(b *bytes.Buffer, arch string, width int) {
	n := width / 64
	fmt.Fprintf(b, "func scaleDense%s%d(values []int64,factor,low,high int64) int {\nlo,hi:=archsimd.BroadcastInt64x%d(low),archsimd.BroadcastInt64x%d(high)\nb:=archsimd.BroadcastUint64x%d(uint64(factor))\n", arch, width, n, n, n)
	if arch == "amd64" && width < 512 {
		b.WriteString("bl,bh:=b.ReshapeToUint32s(),b.ShiftAllRight(32).ReshapeToUint32s()\n")
	}
	if arch == "arm64" {
		b.WriteString("b32:=b.ReshapeToUint32s()\nbl,bh:=b32.ConcatEven(b32),b32.ConcatOdd(b32)\n")
	}
	b.WriteString("row:=0\nfor ;row+8<=len(values);row+=8 {\nblock:=values[row:row+8]\nvar bad uint64\n")
	for off := 0; off < 8; off += n {
		fmt.Fprintf(b, "x%d:=archsimd.LoadInt64x%d(block[%d:])\nf%d:=x%d.Less(lo).Or(x%d.Greater(hi))\n", off, n, off, off, off, off)
		if arch == "amd64" {
			fmt.Fprintf(b, "bad|=uint64(f%d.ToBits())<<%d\n", off, off)
		} else {
			fmt.Fprintf(b, "m%d:=f%d.ToInt64x2()\nbad|=((uint64(m%d.GetElem(0))>>63)|((uint64(m%d.GetElem(1))>>63)<<1))<<%d\n", off, off, off, off, off)
		}
	}
	b.WriteString("if bad!=0 {\nend:=bits.TrailingZeros64(bad)\n")
	if arch == "amd64" {
		b.WriteString("archsimd.ClearAVXUpperBits()\n")
	}
	b.WriteString("for i:=0;i<end;i++ {block[i]*=factor}\nreturn row+end\n}\n")
	for off := 0; off < 8; off += n {
		fmt.Fprintf(b, "{x:=x%d\n", off)
		if arch == "amd64" && width == 512 {
			b.WriteString("result:=x.ToBits().Mul(b).BitsToInt64()\n")
		} else if arch == "amd64" {
			b.WriteString("a:=x.ToBits()\nal,ah:=a.ReshapeToUint32s(),a.ShiftAllRight(32).ReshapeToUint32s()\nresult:=al.MulWidenEven(bl).Add(ah.MulWidenEven(bl).Add(al.MulWidenEven(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		} else {
			b.WriteString("a32:=x.ToBits().ReshapeToUint32s()\nal,ah:=a32.ConcatEven(a32),a32.ConcatOdd(a32)\nresult:=al.MulWidenLo(bl).Add(ah.MulWidenLo(bl).Add(al.MulWidenLo(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		}
		fmt.Fprintf(b, "result.Store(block[%d:])\n}\n", off)
	}
	b.WriteString("}\n")
	if arch == "amd64" {
		b.WriteString("archsimd.ClearAVXUpperBits()\n")
	}
	b.WriteString("for ;row<len(values);row++ {x:=values[row];if x<low||x>high{return row};values[row]=x*factor}\nreturn -1\n}\n")
}

func emitScaleMaskedGroup(b *bytes.Buffer, arch string, width int) {
	n := width / 64
	b.WriteString("for ;off+8<=rows;off+=8 {\nactive:=word>>uint(off)&255\nif active==0 {continue}\nblock:=values[base+off:base+off+8]\nvar bad uint64\n")
	for i := 0; i < 8; i += n {
		fmt.Fprintf(b, "x%d:=archsimd.LoadInt64x%d(block[%d:])\nf%d:=x%d.Less(lo).Or(x%d.Greater(hi))\n", i, n, i, i, i, i)
		if arch == "amd64" {
			fmt.Fprintf(b, "bad|=uint64(f%d.ToBits())<<%d\n", i, i)
		} else {
			fmt.Fprintf(b, "m%d:=f%d.ToInt64x2()\nbad|=((uint64(m%d.GetElem(0))>>63)|((uint64(m%d.GetElem(1))>>63)<<1))<<%d\n", i, i, i, i, i)
		}
	}
	b.WriteString("bad&=active\nif bad!=0 {\nend:=bits.TrailingZeros64(bad)\n")
	if arch == "amd64" {
		b.WriteString("archsimd.ClearAVXUpperBits()\n")
	}
	b.WriteString("for i:=0;i<end;i++ {if active&(uint64(1)<<uint(i))!=0 {block[i]*=factor}}\nreturn base+off+end\n}\n")
	for i := 0; i < 8; i += n {
		fmt.Fprintf(b, "{x:=x%d\n", i)
		if arch == "amd64" && width == 512 {
			b.WriteString("result:=x.ToBits().Mul(b).BitsToInt64()\n")
		} else if arch == "amd64" {
			b.WriteString("a:=x.ToBits()\nal,ah:=a.ReshapeToUint32s(),a.ShiftAllRight(32).ReshapeToUint32s()\nresult:=al.MulWidenEven(bl).Add(ah.MulWidenEven(bl).Add(al.MulWidenEven(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		} else {
			b.WriteString("a32:=x.ToBits().ReshapeToUint32s()\nal,ah:=a32.ConcatEven(a32),a32.ConcatOdd(a32)\nresult:=al.MulWidenLo(bl).Add(ah.MulWidenLo(bl).Add(al.MulWidenLo(bh)).ShiftAllLeft(32)).BitsToInt64()\n")
		}
		fmt.Fprintf(b, "selected:=archsimd.BroadcastUint64x%d(active>>%d).And(weights).NotEqual(archsimd.Uint64x%d{})\nresult.IfElse(selected,x).Store(block[%d:])\n}\n", n, i, n, i)
	}
	b.WriteString("}\n")
}
