package main

import (
	"bytes"
	"fmt"
	"strings"
)

// generateCheckedInteger emits operation-specialized loops. All masks stay in
// registers or bitmap words; no row-sized or per-vector scratch is needed.
func generateCheckedInteger(arch string) []byte {
	var b bytes.Buffer
	build := "goexperiment.simd && " + arch
	if arch == "other" {
		build = "goexperiment.simd && !amd64 && !arm64"
	}
	fmt.Fprintf(&b, "//go:build %s\n\n// Code generated by internal/cmd/gensimd; DO NOT EDIT.\n\npackage kernel\n\n", build)
	if arch == "other" {
		b.WriteString("func installCheckedIntegerSIMD(set *Set, mode Mode, vectorBits int) {}\n")
		return b.Bytes()
	}
	b.WriteString("import (\"gocolumn/memory\"; \"math/bits\"; \"simd/archsimd\")\n\n")
	widths := []int{128}
	if arch == "amd64" {
		widths = []int{128, 256, 512}
	}
	b.WriteString("func installCheckedIntegerSIMD(set *Set, mode Mode, vectorBits int) {\nif mode == ModeScalar || !nativeSIMDAvailable() { return }\n")
	if arch == "amd64" {
		b.WriteString("if !amd64ComparisonWidthSupported(vectorBits) { return }\n")
	}
	b.WriteString("switch vectorBits {\n")
	for _, width := range widths {
		fmt.Fprintf(&b, "case %d:\n", width)
		for _, typ := range []string{"Int64", "Uint64"} {
			for _, op := range []string{"Add", "Sub", "Mul"} {
				fmt.Fprintf(&b, "set.d.arithmetic%s[Arithmetic%s] = checked%s%s%s%d\nid%s%s, _ := ArithmeticID(memory.Type%s, Arithmetic%s)\nset.setCapability(id%s%s, KernelCapability{HardwareSIMD:true, VectorBits:%d, Backend: %q})\n", typ, op, arch, typ, op, width, typ, op, typ, op, typ, op, width, "archsimd-"+arch+"-checked")
			}
		}
	}
	b.WriteString("}\n}\n\n")
	for _, width := range widths {
		lanes := width / 64
		u := fmt.Sprintf("archsimd.Uint64x%d", lanes)
		// A base-2^32 long multiplication, with intermediates proven not to overflow.
		fmt.Fprintf(&b, `// checkedProduct%s%d returns the exact unsigned 128-bit product in two vectors.
// With B=2^32 and each limb < B, t <= B^2-B-1 and w1 <= B^2-B.
// Thus none of the intermediate carries are lost. The high half fits by definition.
func checkedProduct%s%d(a,b %s) (lo,hi %s) {
`, arch, width, arch, width, u, u)
		fmt.Fprintf(&b, "lowMask := archsimd.BroadcastUint64x%d(0xffffffff)\n", lanes)
		if arch == "amd64" && width < 512 {
			b.WriteString("al, bl := a.ReshapeToUint32s(), b.ReshapeToUint32s()\nah, bh := a.ShiftAllRight(32).ReshapeToUint32s(), b.ShiftAllRight(32).ReshapeToUint32s()\nw0 := al.MulWidenEven(bl)\nt := ah.MulWidenEven(bl).Add(w0.ShiftAllRight(32))\nw1 := t.And(lowMask).Add(al.MulWidenEven(bh))\nhi = ah.MulWidenEven(bh).Add(t.ShiftAllRight(32)).Add(w1.ShiftAllRight(32))\n")
		} else if arch == "amd64" {
			b.WriteString("al,bl := a.And(lowMask),b.And(lowMask)\nah,bh := a.ShiftAllRight(32),b.ShiftAllRight(32)\nw0 := al.Mul(bl)\nt := ah.Mul(bl).Add(w0.ShiftAllRight(32))\nw1 := t.And(lowMask).Add(al.Mul(bh))\nhi = ah.Mul(bh).Add(t.ShiftAllRight(32)).Add(w1.ShiftAllRight(32))\n")
		} else {
			b.WriteString("a32,b32 := a.ReshapeToUint32s(),b.ReshapeToUint32s()\nal,bl := a32.ConcatEven(a32),b32.ConcatEven(b32)\nah,bh := a32.ConcatOdd(a32),b32.ConcatOdd(b32)\nw0 := al.MulWidenLo(bl)\nt := ah.MulWidenLo(bl).Add(w0.ShiftAllRight(32))\nw1 := t.And(lowMask).Add(al.MulWidenLo(bh))\nhi = ah.MulWidenLo(bh).Add(t.ShiftAllRight(32)).Add(w1.ShiftAllRight(32))\n")
		}
		b.WriteString("lo = w1.ShiftAllLeft(32).Add(w0.And(lowMask))\nreturn\n}\n\n")
		for _, typ := range []string{"Int64", "Uint64"} {
			for _, op := range []string{"Add", "Sub", "Mul"} {
				gt := strings.ToLower(typ)
				fmt.Fprintf(&b, `func checked%s%s%s%d(left,right,out []%s, validity, overflow memory.Bitmap) int {
prepareIntegerArithmetic(len(left),len(left),len(right),len(out),overflow)
if checkedIntegerPartialOverlap(left,right,out) { return scalar%s%s(left,right,out,validity,overflow) }
first := -1
for wi:=0; wi<memory.WordsFor(len(left)); wi++ {
base:=wi*64
rows:=min(64,len(left)-base)
validWord:=bitmapWord(validity,wi)&memory.TailMask(rows)
if validWord==0 { clear(out[base:base+rows]); continue }
var failedWord uint64
off:=0
`, arch, typ, op, width, gt, typ, op)
				if arch == "amd64" && width < 512 {
					b.WriteString(`// Independent vectors amortize narrow backends' loop and bounds checks.
for ; off+8<=rows; off+=8 {
leftBlock:=left[base+off:base+off+8]
rightBlock:=right[base+off:base+off+8]
outBlock:=out[base+off:base+off+8]
`)
					for part := 0; part < 8; part += lanes {
						fmt.Fprintf(&b, "{\nlaneOffset:=off+%d\na:=archsimd.Load%sx%d(leftBlock[%d:])\nb:=archsimd.Load%sx%d(rightBlock[%d:])\n", part, typ, lanes, part, typ, lanes, part)
						emitCheckedIntegerVector(&b, arch, typ, op, width)
						fmt.Fprintf(&b, "result.Store(outBlock[%d:])\n}\n", part)
					}
					b.WriteString("}\n")
				}
				fmt.Fprintf(&b, "for ; off+%d<=rows; off+=%d {\nlaneOffset:=off\na:=archsimd.Load%sx%d(left[base+off:])\nb:=archsimd.Load%sx%d(right[base+off:])\n", lanes, lanes, typ, lanes, typ, lanes)
				emitCheckedIntegerVector(&b, arch, typ, op, width)
				b.WriteString("result.Store(out[base+off:])\n}\n")
				if arch == "amd64" {
					b.WriteString("archsimd.ClearAVXUpperBits()\n")
				}
				b.WriteString("for ; off<rows; off++ {\nrow:=base+off\na,b:=left[row],right[row]\n")
				symbol := map[string]string{"Add": "+", "Sub": "-", "Mul": "*"}[op]
				fmt.Fprintf(&b, "value:=a %s b\n", symbol)
				switch {
				case typ == "Int64" && op == "Add":
					b.WriteString("failed:=(a^value)&(b^value)<0\n")
				case typ == "Int64" && op == "Sub":
					b.WriteString("failed:=(a^b)&(a^value)<0\n")
				case typ == "Int64" && op == "Mul":
					b.WriteString("hi,_:=bits.Mul64(uint64(a),uint64(b))\nif a<0 { hi-=uint64(b) }; if b<0 { hi-=uint64(a) }\nfailed:=hi!=uint64(value>>63)\n")
				case op == "Add":
					b.WriteString("failed:=value<a\n")
				case op == "Sub":
					b.WriteString("failed:=a<b\n")
				default:
					b.WriteString("hi,_:=bits.Mul64(a,b)\nfailed:=hi!=0\n")
				}
				b.WriteString(`if failed { failedWord |= uint64(1)<<uint(off) }
out[row]=value
}
failedWord &= validWord
if overflow!=nil { overflow[wi]=failedWord }
if first<0 && failedWord!=0 { first=base+bits.TrailingZeros64(failedWord) }
invalid := ^validWord & memory.TailMask(rows)
for invalid!=0 { lane:=bits.TrailingZeros64(invalid); out[base+lane]=0; invalid &= invalid-1 }
}
return first
}

`)
			}
		}
	}
	return b.Bytes()
}

func emitCheckedIntegerVector(b *bytes.Buffer, arch, typ, op string, width int) {
	lanes := width / 64

	switch op {
	case "Add", "Sub":
		fmt.Fprintf(b, "result:=a.%s(b)\n", op)
		if typ == "Int64" {
			formula := "a.Xor(result).And(b.Xor(result))"
			if op == "Sub" {
				formula = "a.Xor(b).And(a.Xor(result))"
			}
			fmt.Fprintf(b, "failed:=%s.Less(archsimd.Int64x%d{})\n", formula, lanes)
		} else {
			if op == "Add" {
				b.WriteString("failed:=result.Less(a)\n")
			} else {
				b.WriteString("failed:=a.Less(b)\n")
			}
		}
	case "Mul":
		if typ == "Int64" {
			fmt.Fprintf(b, "au,bu:=a.ToBits(),b.ToBits()\nlo,hi:=checkedProduct%s%d(au,bu)\nzero:=archsimd.Uint64x%d{}\n// Convert the unsigned product high half to the signed product high half.\nhi=hi.Sub(zero.Sub(au.ShiftAllRight(63)).And(bu)).Sub(zero.Sub(bu.ShiftAllRight(63)).And(au))\n// A signed product fits iff its high half is the sign extension of its low half.\nfailed:=hi.NotEqual(zero.Sub(lo.ShiftAllRight(63)))\nresult:=lo.BitsToInt64()\n", arch, width, lanes)
		} else {
			fmt.Fprintf(b, "result,hi:=checkedProduct%s%d(a,b)\nfailed:=hi.NotEqual(archsimd.Uint64x%d{})\n", arch, width, lanes)
		}
	}
	if arch == "amd64" {
		b.WriteString("failedWord |= uint64(failed.ToBits()) << uint(laneOffset)\n")
	} else {
		b.WriteString("mask:=failed.ToInt64x2()\nfailedWord |= ((uint64(mask.GetElem(0))>>63) | ((uint64(mask.GetElem(1))>>63)<<1)) << uint(laneOffset)\n")
	}
}
