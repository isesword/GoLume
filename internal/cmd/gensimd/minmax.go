package main

import (
	"bytes"
	"fmt"
	"strings"
)

// generateMinMaxSIMD specializes typed loads while sharing the unsigned order-key
// reduction. Float keys sort signed zeros correctly and exclude NaNs explicitly.
func generateMinMaxSIMD() []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by gensimd; DO NOT EDIT.
//go:build goexperiment.simd

package kernel

import (
 "gocolumn/memory"
 "math"
 "math/bits"
 "simd"
)

func installMinMaxSIMD(set *Set, mode Mode, vectorBits int) {
 if mode == ModeScalar || !nativeSIMDAvailable() { return }
 if vectorBits != 128 && vectorBits != 256 && vectorBits != 512 { return }
 installNarrowMinMaxSIMD(set, vectorBits)
`)
	types := []string{"Int32", "Int64", "Uint32", "Uint64", "Float32", "Float64"}
	for _, t := range types {
		fmt.Fprintf(&b, "set.d.minMax%sMasked = simdMinMax%sMasked\n", t, t)
	}
	b.WriteString("for _, typ := range []memory.DataType{")
	for _, t := range types {
		fmt.Fprintf(&b, "memory.Type%s,", t)
	}
	b.WriteString(`} {
 id, _ := MinMaxID(typ)
 set.setCapability(id, KernelCapability{HardwareSIMD:true, VectorBits:vectorBits, Backend:"portable-simd"})
 }
}
`)
	for _, t := range types {
		w := t[len(t)-2:]
		low := strings.ToLower(t)
		floating := strings.HasPrefix(t, "Float")
		signed := strings.HasPrefix(t, "Int")
		fmt.Fprintf(&b, `
func simdMinMax%sMasked(v []%s, mask uint64) (%s,%s) {
 mask = checkedMinMaxMask(len(v),mask)
 if mask == 0 { return 0,0 }
 lanes := simd.Uint%ss{}.Len()
 if len(v) < lanes { return scalarMinMaxMasked(v,mask) }
 lo := simd.BroadcastUint%ss(^uint%s(0))
 hi := simd.Uint%ss{}
 weights := simd.LoadUint%ss(sumWeights%s[:])
`, t, low, low, low, w, w, w, w, w, w)
		if signed || floating {
			fmt.Fprintf(&b, "sign := simd.BroadcastUint%ss(uint%s(1)<<%s)\n", w, w, map[string]string{"32": "31", "64": "63"}[w])
		}
		fmt.Fprintf(&b, `off := 0
 for ; off+lanes <= len(v); off += lanes {
 selected := simd.BroadcastUint%ss(uint%s(mask>>uint(off))).And(weights).NotEqual(simd.Uint%ss{})
 x := simd.Load%ss(v[off:])
`, w, w, w, t)
		switch {
		case floating:
			b.WriteString("selected = selected.And(x.Equal(x))\n")
			b.WriteString("raw := x.ToBits()\nkey := raw.Not().IfElse(raw.And(sign).NotEqual(simd.Uint" + w + "s{}),raw.Xor(sign))\n")
		case signed:
			b.WriteString("key := x.ToBits().Xor(sign)\n")
		default:
			b.WriteString("key := x\n")
		}
		b.WriteString("lo = key.IfElse(selected.And(key.Less(lo)),lo)\nhi = key.IfElse(selected.And(key.Greater(hi)),hi)\n}\n")
		fmt.Fprintf(&b, "a,z := reduceMinMaxUint%s(lo,hi)\nfor ; off < len(v); off++ {\n if mask&(uint64(1)<<uint(off)) == 0 { continue }\n x := v[off]\n", w)
		switch {
		case floating:
			fmt.Fprintf(&b, "if x != x { continue }; key := minMaxFloat%sKey(x)\n", w)
		case signed:
			fmt.Fprintf(&b, "key := uint%s(x) ^ (uint%s(1)<<%s)\n", w, w, map[string]string{"32": "31", "64": "63"}[w])
		default:
			b.WriteString("key := x\n")
		}
		b.WriteString("a = min(a,key); z = max(z,key)\n}\n")
		switch {
		case floating:
			fmt.Fprintf(&b, "if a == ^uint%s(0) { x := v[63-bits.LeadingZeros64(mask)]; return x,x }; return minMaxFloat%sFromKey(a),minMaxFloat%sFromKey(z)\n", w, w, w)
		case signed:
			fmt.Fprintf(&b, "return %s(a ^ (uint%s(1)<<%s)), %s(z ^ (uint%s(1)<<%s))\n", low, w, map[string]string{"32": "31", "64": "63"}[w], low, w, map[string]string{"32": "31", "64": "63"}[w])
		default:
			b.WriteString("return a,z\n")
		}
		b.WriteString("}\n")
	}
	for _, w := range []string{"32", "64"} {
		sign := map[string]string{"32": "31", "64": "63"}[w]
		fmt.Fprintf(&b, `func minMaxFloat%sKey(x float%s) uint%s {
 raw := math.Float%sbits(x)
 if raw & (uint%s(1)<<%s) != 0 { return ^raw }
 return raw ^ (uint%s(1)<<%s)
}
func minMaxFloat%sFromKey(x uint%s) float%s {
 if x & (uint%s(1)<<%s) == 0 { return math.Float%sfrombits(^x) }
 return math.Float%sfrombits(x ^ (uint%s(1)<<%s))
}
`, w, w, w, w, w, sign, w, sign, w, w, w, w, sign, w, w, w, sign)
	}
	return b.Bytes()
}
